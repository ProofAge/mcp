#!/usr/bin/env python3
"""Write the README tools block and docs/TOOLS.md from tools.json and tools.meta.json.

Usage: python3 scripts/render.py [--check]
--check exits 1 if either file would change.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
START, END = "<!-- tools:start -->", "<!-- tools:end -->"
GROUPS = ["Workspaces and keys", "Verifications", "Webhooks", "Blocklist", "Personal data", "Docs"]
ROLE_NAMES = {
    "administrator": "Administrator",
    "developer": "Developer",
    "support_specialist": "Support specialist",
}


def load():
    tools = json.loads((ROOT / "tools.json").read_text(encoding="utf-8"))
    meta = json.loads((ROOT / "tools.meta.json").read_text(encoding="utf-8"))
    return tools, meta


def roles(tool):
    return ", ".join(ROLE_NAMES.get(r, r) for r in tool["roles"])


def kind(tool):
    return "read" if tool["read_only"] else "write"


def grouped(tools, meta):
    order = GROUPS + sorted({m["group"] for m in meta.values()} - set(GROUPS))
    out = []
    for g in order:
        items = [t for t in tools if meta[t["name"]]["group"] == g]
        if items:
            out.append((g, items))
    return out


def readme_block(tools, meta):
    lines = [f"The server has {len(tools)} tools.", ""]
    for g, items in grouped(tools, meta):
        lines += [f"### {g}", "", "| Tool | What it does | Type | Roles |", "| --- | --- | --- | --- |"]
        for t in items:
            lines.append(f"| `{t['name']}` | {meta[t['name']]['summary']} | {kind(t)} | {roles(t)} |")
        lines.append("")
    lines.append("Full descriptions, as your assistant reads them: [docs/TOOLS.md](docs/TOOLS.md).")
    return "\n".join(lines)


def tools_md(tools, meta):
    lines = [
        "<!-- Generated by scripts/render.py from tools.json. Do not edit. -->",
        "",
        "# ProofAge MCP server tools",
        "",
        "Generated by scripts/render.py from tools.json. Do not edit.",
        "",
        f"{len(tools)} tools. Each description is the text your assistant reads.",
        "",
    ]
    for g, items in grouped(tools, meta):
        lines += [f"## {g}", ""]
        for t in items:
            lines += [
                f"### `{t['name']}`",
                "",
                f"Type: {kind(t)}. Roles: {roles(t)}.",
                "",
                t["description"],
                "",
            ]
    return "\n".join(lines).rstrip() + "\n"


def readme_text(tools, meta):
    path = ROOT / "README.md"
    text = path.read_text(encoding="utf-8")
    if START not in text or END not in text:
        sys.exit("README.md has no tools markers")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    return head + START + "\n" + readme_block(tools, meta) + "\n" + END + tail


def main():
    tools, meta = load()
    new = {ROOT / "README.md": readme_text(tools, meta), ROOT / "docs" / "TOOLS.md": tools_md(tools, meta)}
    if "--check" in sys.argv:
        stale = [str(p.relative_to(ROOT)) for p, t in new.items() if not p.exists() or p.read_text(encoding="utf-8") != t]
        if stale:
            print("Out of date, run python3 scripts/render.py: " + ", ".join(stale))
            sys.exit(1)
        print("render: up to date")
        return
    for p, t in new.items():
        p.write_text(t, encoding="utf-8")
    print("Wrote README.md block and docs/TOOLS.md")


if __name__ == "__main__":
    main()
